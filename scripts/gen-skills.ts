#!/usr/bin/env node
// Single source of truth for the skill registry.
// Discovers skills from the filesystem (skills/<category>/<name>/SKILL.md
// frontmatter) and projects them into eleven artifacts: README.md's table, each
// skills/<category>/README.md, .claude-plugin/plugin.json, skills.sh.json, the
// config contract mirrored into every skill that hosts it (and the resolver into
// every skill that names it), the author-authority block mirrored into every skill
// that reads third-party text, the check-command contract mirrored into every skill
// that runs the gate, the single-flight-lock spec mirrored into the two work-loop
// unit skills, the plan-presentation rule mirrored into every skill that presents a
// plan, the report-lead rule mirrored into every skill that ends in a report, and the
// forge/host resolution rule mirrored into every skill that drives a forge.
//
//   node scripts/gen-skills.ts           # rewrite whichever have drifted
//   node scripts/gen-skills.ts --check   # exit 1 if any is stale (CI)
//   node scripts/gen-skills.ts --paths   # list SKILL.md paths (for scripts)

import {
  readFileSync,
  writeFileSync,
  readdirSync,
  mkdirSync,
  rmSync,
  existsSync
} from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import process from 'node:process';

export const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

function readText(file: string): string {
  try {
    return readFileSync(file, 'utf8');
  } catch (err) {
    const error = err as NodeJS.ErrnoException;
    error.path ??= file;
    error.message = `${file}: ${error.message}`;
    throw error;
  }
}

// A snapshot belongs to one run: discovery and mirroring see the same documents,
// while the next run sees edits made since then. Only an absent file is optional.
class Documents {
  private contents = new Map<string, string | undefined>();

  read(file: string): string | undefined {
    if (!this.contents.has(file)) {
      try {
        this.contents.set(file, readText(file));
      } catch (err) {
        if ((err as NodeJS.ErrnoException).code !== 'ENOENT') throw err;
        this.contents.set(file, undefined);
      }
    }
    return this.contents.get(file);
  }
}

// Every path the generator touches, derived from one root. The root is an argument
// rather than a module constant because the artifacts are what needs checking, and
// checking them means letting a run produce them: a test points the whole generator
// at a fixture tree and lets it write there. Wired to a constant these functions can
// only ever be run against this repo, which is why none of them had a test.
export interface Paths {
  root: string;
  skills: string;
  readme: string;
  plugin: string;
  skillsSh: string;
  configBlock: string;
  authorityBlock: string;
  verifyBlock: string;
  worklockBlock: string;
  planBlock: string;
  tldrBlock: string;
  forgeBlock: string;
  resolver: string;
}

export function paths(root: string): Paths {
  return {
    root,
    skills: join(root, 'skills'),
    readme: join(root, 'README.md'),
    plugin: join(root, '.claude-plugin', 'plugin.json'),
    skillsSh: join(root, 'skills.sh.json'),
    configBlock: join(root, 'scripts', 'config-block.md'),
    authorityBlock: join(root, 'scripts', 'authority-block.md'),
    verifyBlock: join(root, 'scripts', 'verify-block.md'),
    worklockBlock: join(root, 'scripts', 'worklock-block.md'),
    planBlock: join(root, 'scripts', 'plan-block.md'),
    tldrBlock: join(root, 'scripts', 'tldr-block.md'),
    forgeBlock: join(root, 'scripts', 'forge-block.md'),
    resolver: join(root, 'scripts', 'resolve-config.sh')
  };
}

const START = '<!-- skills:start -->';
const END = '<!-- skills:end -->';
const NOTE =
  '<!-- Generated by `pnpm skills:sync` — edit skill frontmatter, not this table. -->';

// A tag, not an HTML comment: a SKILL.md is a prompt, so the block's boundary should be
// visible to the model reading it rather than hidden in a comment. It carries no
// attributes — provenance would have to name files the installed skill does not have.
// Matched by name, so an attribute added later cannot orphan a committed block.
const CONFIG_OPEN = '<skills-config>';
const CONFIG_OPEN_RE = /<skills-config\b[^>]*>/;
const CONFIG_END = '</skills-config>';

// The Agent Skills spec caps `description` at 1024 characters, and that cap is a cliff:
// a skill one character over is non-conformant, and nothing about writing a description
// makes its length visible. So the budget enforced here is the lower one — the house
// budget — leaving 64 characters of shoulder above it. That is roughly one trigger phrase
// plus its other-language variant, so the ordinary reason a description gets edited never
// has to be length-neutral, and going over is caught while the skill is still conformant.
const DESCRIPTION_CAP = 1024;
const DESCRIPTION_BUDGET = 960;

// Node runs this file directly by erasing the types, so only erasable syntax is
// available here: no enums, no namespaces, no parameter properties.
type Category = 'repo' | 'work' | 'docs' | 'meta';

export interface Skill {
  category: Category;
  dir: string;
  path: string;
  name: string;
  summary: string;
  frontmatter: { summary?: string; description?: string };
}

export interface Group {
  category: Category;
  title: string;
  description: string;
  skills: Skill[];
}

// Drift is compared on collapsed whitespace throughout: oxfmt rewraps the mirrored
// markdown and pads the generated tables, so a reflow must not read as a change while a
// reworded sentence still does. Defined once — three copies of this is where the
// artifacts would start disagreeing about what counts as drift.
const norm = (text: string) => text.replace(/\s+/g, ' ').trim();

export function parseFrontmatter(raw: string): Record<string, string> {
  const match = raw.match(/^---\n([\s\S]*?)\n---/);
  const out: Record<string, string> = {};
  if (!match?.[1]) return out;
  // One level of nesting is understood: a key with no inline value (e.g.
  // `metadata:`) becomes the parent of the indented `child: value` lines that
  // follow, flattened to `metadata.child` — where the house `summary` now lives.
  let parent = '';
  for (const line of match[1].split('\n')) {
    let nested: RegExpMatchArray | null = null;
    if (parent) nested = line.match(/^\s+([A-Za-z][\w-]*):\s?(.*)$/);
    if (nested?.[2]) {
      out[`${parent}.${nested[1]}`] = nested[2].trim();
      continue;
    }
    const field = line.match(/^([A-Za-z][\w-]*):\s?(.*)$/);
    const [, key, value] = field ?? [];
    if (!key) continue;
    if (value) {
      out[key] = value.trim();
      parent = '';
    } else {
      parent = key;
    }
  }
  return out;
}

// Fallback when a skill has no `metadata.summary`: the first clause of `description`.
export function deriveSummary(description: string): string {
  const dash = description.search(/\s[—–]\s/);
  const period = description.search(/\.\s/);
  const stops = [dash, period === -1 ? -1 : period + 1].filter((i) => i > 0);
  let cut = stops.length
    ? description.slice(0, Math.min(...stops)).trim()
    : description.trim();
  if (cut.length > 120) {
    const head = cut.slice(0, 117);
    cut = `${head.slice(0, head.lastIndexOf(' '))}…`;
  }
  return cut;
}

// Skills are nested one level deep: skills/<category>/<skill>/SKILL.md. The
// filesystem owns membership — which skill sits in which category — and this
// table owns each category's display metadata and its order. Adding a skill
// means creating a directory; adding a category means one entry here.
const CATEGORIES: Record<Category, { title: string; description: string }> = {
  repo: {
    title: 'Repository & release',
    description:
      "Commits, pull requests, releases and dependency updates — each driven by the repo's own conventions."
  },
  work: {
    title: 'Tracked work',
    description:
      'Issues, the two AI work loops (implement and review), handing work between sessions, and summarising one.'
  },
  docs: {
    title: 'Docs & READMEs',
    description:
      'Generate and maintain project documentation, READMEs and terminal demos in the house style.'
  },
  meta: {
    title: 'Meta',
    description: 'Configure the skills themselves, per repo.'
  }
};

export function discoverSkills(p: Paths, documents = new Documents()): Skill[] {
  const categories = readdirSync(p.skills, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name);

  const unknown = categories.filter((c) => !(c in CATEGORIES));
  if (unknown.length) {
    throw new Error(
      `skills/${unknown.join(', skills/')}: not a known category — add it to CATEGORIES in scripts/gen-skills.ts`
    );
  }

  // Category order comes from CATEGORIES; skills sort alphabetically within one.
  return (Object.keys(CATEGORIES) as Category[])
    .filter((category) => categories.includes(category))
    .flatMap((category) =>
      readdirSync(join(p.skills, category), { withFileTypes: true })
        .filter((entry) => entry.isDirectory())
        .map((entry) => entry.name)
        .sort()
        .map((dir): Skill | null => {
          const raw = documents.read(join(p.skills, category, dir, 'SKILL.md'));
          if (raw === undefined) return null;
          const fm = parseFrontmatter(raw);
          const summary = fm['metadata.summary'];
          return {
            category,
            dir,
            path: `${category}/${dir}`,
            name: fm.name ?? dir,
            summary: summary ?? deriveSummary(fm.description ?? ''),
            frontmatter: { summary, description: fm.description }
          };
        })
        .filter((skill) => skill !== null)
    );
}

// [{ category, title, description, skills: [...] }] in CATEGORIES order.
export function byCategory(skills: Skill[]): Group[] {
  return (
    Object.entries(CATEGORIES) as [Category, (typeof CATEGORIES)[Category]][]
  )
    .map(([category, meta]) => ({
      category,
      ...meta,
      skills: skills.filter((s) => s.category === category)
    }))
    .filter((group) => group.skills.length > 0);
}

export function renderTable(groups: Group[]): string {
  const sections = groups.flatMap((group) => [
    '',
    `### ${group.title}`,
    '',
    group.description,
    '',
    '| Skill | Description |',
    '| :-- | :-- |',
    ...group.skills.map(
      (s) => `| [\`${s.name}\`](skills/${s.path}/SKILL.md) | ${s.summary} |`
    )
  ]);
  return [START, NOTE, ...sections, END].join('\n');
}

// Parse the committed block semantically so oxfmt's column alignment and its
// table-padding never trip the drift check. Headings and rows both matter —
// a skill silently moving category has to register as drift.
export function parseTable(block: string): string[] {
  const tokens: string[] = [];
  for (const line of block.split('\n')) {
    const heading = line.match(/^###\s+(.*?)\s*$/);
    if (heading) {
      tokens.push(`h\t${heading[1]}`);
      continue;
    }
    const row = line.match(
      /^\|\s*\[`([^`]+)`\]\(([^)]+)\)\s*\|\s*(.*?)\s*\|\s*$/
    );
    if (row) tokens.push(`r\t${row[1]}\t${row[2]}\t${row[3]}`);
  }
  return tokens;
}

export function expectedTableTokens(groups: Group[]): string[] {
  return groups.flatMap((group) => [
    `h\t${group.title}`,
    ...group.skills.map(
      (s) => `r\t${s.name}\tskills/${s.path}/SKILL.md\t${s.summary}`
    )
  ]);
}

export function syncReadme(p: Paths, groups: Group[], check: boolean): boolean {
  const content = readText(p.readme);
  const from = content.indexOf(START);
  const to = content.indexOf(END);
  if (from === -1 || to === -1) {
    throw new Error(`README.md is missing the ${START} / ${END} markers`);
  }
  const block = content.slice(from, to + END.length);
  const current = parseTable(block);
  const expected = expectedTableTokens(groups);
  const drift = JSON.stringify(current) !== JSON.stringify(expected);
  if (drift && !check) {
    writeFileSync(p.readme, content.replace(block, renderTable(groups)));
  }
  return drift;
}

// One README per category — the section landing a reader hits when they open
// skills/<category>/. Fully generated; edit skill frontmatter, not these.
export function renderCategoryReadme(group: Group): string {
  return `${[
    `<!-- Generated by \`pnpm skills:sync\` — edit skill frontmatter, not this file. -->`,
    '',
    `# ${group.title}`,
    '',
    group.description,
    '',
    ...group.skills.map(
      (s) => `- **[${s.name}](./${s.dir}/SKILL.md)** — ${s.summary}`
    ),
    '',
    `Back to [all skills](../README.md).`
  ].join('\n')}\n`;
}

export function syncCategoryReadmes(
  p: Paths,
  groups: Group[],
  check: boolean
): string[] {
  const stale: string[] = [];
  for (const group of groups) {
    const file = join(p.skills, group.category, 'README.md');
    const expected = renderCategoryReadme(group);
    let current = '';
    try {
      current = readText(file);
    } catch (err) {
      if ((err as NodeJS.ErrnoException).code !== 'ENOENT') throw err;
      current = '';
    }
    if (norm(current) !== norm(expected)) {
      stale.push(`skills/${group.category}/README.md`);
      if (!check) writeFileSync(file, expected);
    }
  }
  return stale;
}

// Two artifacts are one key inside a JSON file the generator does not otherwise own, so
// the mechanic is shared and only the projection differs. Every other key in the file
// survives the rewrite — that is the whole reason this reads and re-serializes rather
// than writing the key's value out on its own.
function syncJsonKey(
  file: string,
  key: string,
  expected: unknown,
  check: boolean
): boolean {
  const data = JSON.parse(readText(file)) as Record<string, unknown>;
  const drift = JSON.stringify(data[key] ?? []) !== JSON.stringify(expected);
  if (drift && !check) {
    data[key] = expected;
    writeFileSync(file, `${JSON.stringify(data, null, 2)}\n`);
  }
  return drift;
}

// skills.sh.json drives how skills.sh displays the collection. Projected from
// the same categories so the website grouping can never drift from the folders.
export function syncSkillsSh(
  p: Paths,
  groups: Group[],
  check: boolean
): boolean {
  return syncJsonKey(
    p.skillsSh,
    'groupings',
    groups.map((group) => ({
      title: group.title,
      description: group.description,
      skills: group.skills.map((s) => s.name)
    })),
    check
  );
}

export function syncPlugin(p: Paths, skills: Skill[], check: boolean): boolean {
  return syncJsonKey(
    p.plugin,
    'skills',
    skills.map((s) => `./skills/${s.path}`),
    check
  );
}

// A skill can be installed on its own, so it must not link to another skill or to a
// file at the repo root — the link resolves to nothing on the installed copy. Anything
// shared is therefore mirrored *into* each skill and kept identical from here: the
// config contract as text between markers, and the resolver as a real file the skill
// can execute. A skill opts in by carrying the markers.
//
// The two opt-ins are separate, because the two things are: the contract is *prose*, and a
// skill that cannot run without a named sibling may read that sibling's copy instead of
// shipping one; the resolver is a file it *executes*, and no naming makes another folder's
// copy runnable. So the resolver follows the mention rather than the block — every block
// host names it (the block links it), plus the queue skills, which delegate the prose and
// still run the script. Keying it on the block alone would freeze their copy at whatever
// was last committed, drift-checked by nothing.
const RESOLVER_PATH = 'templates/resolve-config.sh';
// Split one canonical source into ordered sections. All contracts share the same
// marker validation; only verify composes its base and install sections.
function sections(file: string, names: string[]): string[] {
  const raw = readText(file);
  const markers = names.map((name) => `<!-- ${name} -->`);
  const offsets = markers.map((marker) => raw.indexOf(marker));
  for (const [index, offset] of offsets.entries()) {
    if (
      offset === -1 ||
      (index > 0 && offset <= (offsets[index - 1] as number))
    ) {
      throw new Error(`${file}: missing or misordered ${markers.join(' / ')}`);
    }
  }
  return offsets.map((offset, index) =>
    raw
      .slice(offset + (markers[index] as string).length, offsets[index + 1])
      .trim()
  );
}

interface Contract {
  label: string;
  variants: { open: string; end: string; body: string }[];
}

function variant(tag: string, body: string) {
  return { open: `<skills-${tag}>`, end: `</skills-${tag}>`, body };
}

function contracts(p: Paths): Contract[] {
  const [full, reduced] = sections(p.authorityBlock, [
    'authority:full',
    'authority:reduced'
  ]);
  const [base, install] = sections(p.verifyBlock, [
    'verify:base',
    'verify:isolated'
  ]);
  return [
    {
      label: 'authority',
      variants: [
        variant('authority', full as string),
        variant('authority-reduced', reduced as string)
      ]
    },
    {
      label: 'verify',
      variants: [
        variant('verify', base as string),
        variant('verify-isolated', `${base}\n\n${install}`)
      ]
    },
    ...(
      [
        ['worklock', p.worklockBlock],
        ['plan', p.planBlock],
        ['tldr', p.tldrBlock],
        ['forge', p.forgeBlock]
      ] as const
    ).map(([label, file]) => ({
      label,
      variants: [variant(label, sections(file, [`${label}:body`])[0] as string)]
    }))
  ];
}

// The mirrored block opens with a level-3 heading, so it belongs under "## Config".
// Placed anywhere else it silently reads as part of the preceding section — a queue
// skill's block landed under "## Workflow" and became its last step. Rewriting the
// block cannot fix where it sits, so placement is asserted rather than repaired.
export function assertPlacement(
  content: string,
  from: number,
  where: string
): void {
  const headings = content.slice(0, from).match(/^## .*$/gm);
  const under = headings ? headings[headings.length - 1] : null;
  if (under !== '## Config') {
    throw new Error(
      `${where}: <skills-config> sits under ${under ?? 'no heading'} — move it under a "## Config" heading`
    );
  }
}

function syncContracts(
  p: Paths,
  skills: Skill[],
  check: boolean,
  documents: Documents
): string[] {
  const stale: string[] = [];
  const config = sections(p.configBlock, ['config:body'])[0] as string;
  const expectedConfig = `${CONFIG_OPEN}\n\n${config}\n\n${CONFIG_END}`;
  const resolver = readText(p.resolver);
  const mirrored = contracts(p);

  for (const skill of skills) {
    const dir = join(p.skills, skill.path);
    let shipsResolver = false;

    for (const name of ['SKILL.md', 'REFERENCE.md']) {
      const file = join(dir, name);
      const original = documents.read(file);
      if (original === undefined) continue;
      let current = original;
      const opening = current.match(CONFIG_OPEN_RE);
      const end = current.indexOf(CONFIG_END);
      if (opening && end !== -1) {
        const from = opening.index as number;
        assertPlacement(current, from, `skills/${skill.path}/${name}`);
        const next =
          current.slice(0, from) +
          expectedConfig +
          current.slice(end + CONFIG_END.length);
        if (norm(next) !== norm(current))
          stale.push(`skills/${skill.path}/${name} config block`);
        current = next;
      }

      for (const contract of mirrored) {
        for (const v of contract.variants) {
          const from = current.indexOf(v.open);
          const to = current.indexOf(v.end);
          if (from === -1 || to === -1) continue;
          const next =
            current.slice(0, from) +
            `${v.open}\n\n${v.body}\n\n${v.end}` +
            current.slice(to + v.end.length);
          if (norm(next) !== norm(current))
            stale.push(`skills/${skill.path}/${name} ${contract.label} block`);
          current = next;
        }
      }

      if (!check && norm(current) !== norm(original))
        writeFileSync(file, current);
      // A newly mirrored config block may introduce the resolver mention in this run.
      if (current.includes(RESOLVER_PATH)) shipsResolver = true;
    }

    const target = join(dir, 'templates', 'resolve-config.sh');
    if (!shipsResolver) {
      if (existsSync(target)) {
        stale.push(`skills/${skill.path}/templates/resolve-config.sh (orphan)`);
        if (!check) rmSync(target);
      }
      continue;
    }

    if (documents.read(target) !== resolver) {
      stale.push(`skills/${skill.path}/templates/resolve-config.sh`);
      if (!check) {
        mkdirSync(join(dir, 'templates'), { recursive: true });
        writeFileSync(target, resolver);
      }
    }
  }
  return stale;
}

// Description limits and YAML punctuation are stricter than our discovery parser.
export function lintFrontmatter(skills: Skill[]): string[] {
  const problems: string[] = [];
  for (const skill of skills) {
    // Length is checked on the raw value, quoted or not: a quoted description counts its
    // two quotes, which errs two characters strict rather than two characters lax.
    const description = skill.frontmatter.description;
    if (description && description.length > DESCRIPTION_BUDGET) {
      problems.push(
        `${skill.path}: \`description\` is ${description.length} chars — over the ${DESCRIPTION_BUDGET} house budget (spec cap ${DESCRIPTION_CAP}); trim it, so the next edit does not have to be length-neutral`
      );
    }

    for (const field of ['summary', 'description'] as const) {
      const value = skill.frontmatter[field];
      if (!value || /^['"]/.test(value.trim())) continue;
      if (value.includes(': ')) {
        problems.push(
          `${skill.path}: \`${field}\` contains ": " (colon+space) — use " — " instead, else skills.sh drops the skill`
        );
      }
      if (value.includes(' #')) {
        problems.push(
          `${skill.path}: \`${field}\` contains " #" (space+hash) — YAML reads it as a comment`
        );
      }
    }
  }
  return problems;
}

// One run, as a value: the exit code and the two streams, returned rather than written.
// Everything a run decides — which mode, which artifacts drifted, what the operator is
// told — is then assertable without spawning a process or capturing stdout, and the
// process boundary below stays the only place that talks to the OS.
export interface RunResult {
  code: number;
  stdout: string;
  stderr: string;
}

export function main(argv: string[], root: string = ROOT): RunResult {
  const mode = argv[0] ?? '--write';
  if (mode !== '--paths' && mode !== '--check' && mode !== '--write') {
    return { code: 2, stdout: '', stderr: `unknown mode: ${mode}\n` };
  }

  const p = paths(root);
  const documents = new Documents();
  const skills = discoverSkills(p, documents);

  if (mode === '--paths') {
    const lines = skills.map((skill) => `skills/${skill.path}/SKILL.md\n`);
    return { code: 0, stdout: lines.join(''), stderr: '' };
  }

  const check = mode === '--check';
  const groups = byCategory(skills);

  const problems = lintFrontmatter(skills);
  if (problems.length) {
    return {
      code: 1,
      stdout: '',
      stderr: `skill frontmatter invalid:\n${problems.map((x) => `  - ${x}`).join('\n')}\n`
    };
  }

  const stale: string[] = [];
  if (syncReadme(p, groups, check)) stale.push('README.md table');
  if (syncPlugin(p, skills, check)) stale.push('plugin.json skills array');
  if (syncSkillsSh(p, groups, check)) stale.push('skills.sh.json groupings');
  stale.push(...syncCategoryReadmes(p, groups, check));
  stale.push(...syncContracts(p, skills, check, documents));

  if (check && stale.length) {
    return {
      code: 1,
      stdout: '',
      stderr: `skills registry out of sync: ${stale.join(', ')}\nrun \`pnpm skills:sync\`\n`
    };
  }

  let state = 'already in sync';
  if (check) state = 'in sync';
  else if (stale.length) state = `updated ${stale.join(', ')}`;
  return {
    code: 0,
    stdout: `skills registry ${state} (${skills.length} skills)\n`,
    stderr: ''
  };
}

// The process boundary, and the whole of it. Importing this file runs no I/O.
if (import.meta.main) {
  const result = main(process.argv.slice(2));
  if (result.stdout) process.stdout.write(result.stdout);
  if (result.stderr) process.stderr.write(result.stderr);
  process.exit(result.code);
}
